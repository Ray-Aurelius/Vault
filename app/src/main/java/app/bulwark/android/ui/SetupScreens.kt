        Spacer(Modifier.height(16.dp))
        Quiet(stringResource(R.string.recovery_more_later))
    }
}

@Composable
fun ShowWordsScreen(recovery: SecretBytes, onDone: () -> Unit, onBack: (() -> Unit)?) {
    val words = remember(recovery) { RecoveryKey.toWords(recovery) }
    Page(title = stringResource(R.string.words_title), onBack = onBack, bottomBar = { PrimaryButton(stringResource(R.string.words_written), onDone) }) {
        Body(stringResource(R.string.words_body))
        Spacer(Modifier.height(12.dp))
        Column(
            Modifier.fillMaxWidth().border(1.dp, MaterialTheme.colorScheme.outline, RoundedCornerShape(12.dp)).padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            for (row in words.chunked(3).withIndex()) {
                Row(Modifier.fillMaxWidth()) {
                    row.value.forEachIndexed { i, w ->
                        val n = row.index * 3 + i + 1
                        Row(Modifier.weight(1f), verticalAlignment = Alignment.CenterVertically) {
                            Text("$n", style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant, modifier = Modifier.width(26.dp))
                            Text(w, style = MaterialTheme.typography.bodyLarge.copy(fontFamily = SourceCodePro), fontWeight = FontWeight.Medium, color = MaterialTheme.colorScheme.onBackground)
                        }
                    }
                }
            }
        }
        Spacer(Modifier.height(12.dp))
        InfoCard(null, stringResource(R.string.words_warning), R.drawable.ic_warning, warning = true)
        Quiet(stringResource(R.string.words_no_copy))
    }
}

@Composable
fun ConfirmWordsScreen(recovery: SecretBytes, onConfirmed: () -> Unit, onShowAgain: () -> Unit) {
    val words = remember(recovery) { RecoveryKey.toWords(recovery) }
    val picks = remember(recovery) { (0 until RecoveryKey.WORDS).shuffled(Random(System.nanoTime())).take(3).sorted() }
    val answers = remember(recovery) { mutableStateListOf("", "", "") }
    var tried by remember { mutableStateOf(false) }
    val correct = picks.indices.all { i -> answers[i].trim().lowercase().let { a -> a.isNotEmpty() && (a == words[picks[i]] || (a.length >= 4 && words[picks[i]].startsWith(a))) } }
    Page(
        title = stringResource(R.string.confirm_words_title), onBack = onShowAgain,
        bottomBar = { PrimaryButton(stringResource(R.string.confirm), { tried = true; if (correct) onConfirmed() }) },
    ) {
        Body(stringResource(R.string.confirm_words_body))
        Spacer(Modifier.height(8.dp))
        picks.forEachIndexed { i, idx ->
            SecretField(
                answers[i], { answers[i] = it }, stringResource(R.string.word_number, idx + 1),
                imeAction = if (i < 2) ImeAction.Next else ImeAction.Done,
                isError = tried && !correct, modifier = Modifier.padding(vertical = 4.dp),
            )
        }
        if (tried && !correct) Text(stringResource(R.string.confirm_words_wrong), color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodyMedium)
        LinkButton(stringResource(R.string.show_words_again), onShowAgain)
    }
}

@Composable
private fun SkipRecoveryScreen(onConfirmed: () -> Unit, onBack: () -> Unit) {
    val phrase = stringResource(R.string.skip_phrase)
    var typed by remember { mutableStateOf("") }
    val ok = typed.trim().equals(phrase, ignoreCase = true)
    Page(title = stringResource(R.string.skip_title), onBack = onBack, bottomBar = { DangerButton(stringResource(R.string.skip_confirm), onConfirmed, enabled = ok) }) {
        InfoCard(null, stringResource(R.string.skip_body), R.drawable.ic_warning, warning = true)
        Spacer(Modifier.height(8.dp))
        Body(stringResource(R.string.skip_type, phrase))
        OutlinedTextField(typed, { typed = it }, modifier = Modifier.fillMaxWidth(), label = { Text(stringResource(R.string.skip_label)) })
        Quiet(stringResource(R.string.not_responsible), Modifier.padding(top = 12.dp))
    }
}

@Composable
fun SecuringScreen(onRun: suspend () -> Unit, onFailed: () -> Unit) {
    var failed by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    LaunchedEffect(Unit) {
        try { onRun() } catch (e: Exception) { failed = true }
    }
    Page {
        Spacer(Modifier.height(96.dp))
        BrandHeader()
        Spacer(Modifier.height(32.dp))
        if (!failed) {
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.Center) { CircularProgressIndicator() }
            Spacer(Modifier.height(16.dp))
            Body(stringResource(R.string.securing_body), Modifier.fillMaxWidth())
        } else {
            InfoCard(stringResource(R.string.securing_failed_title), stringResource(R.string.securing_failed_body), R.drawable.ic_warning, warning = true)
            PrimaryButton(stringResource(R.string.try_again), { scope.launch { onFailed() } })
        }
    }
}
