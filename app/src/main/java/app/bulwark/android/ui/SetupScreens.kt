/**
 * Setup after the Terms: password → recovery choice → (show and confirm 24 words | typed skip) →
 * securing. Secrets live only in memory here (the activity handles rotation itself, so nothing is
 * written into saved state).
 */
@Composable
fun SetupFlow(session: VaultSession) {
    var step by remember { mutableStateOf(SetupStep.PASSWORD) }
    var password by remember { mutableStateOf("") }
    var recovery by remember { mutableStateOf<SecretBytes?>(null) }
    DisposableEffect(Unit) { onDispose { recovery?.close() } }
    BackHandler(enabled = step != SetupStep.PASSWORD && step != SetupStep.SECURING) {
        step = when (step) {
            SetupStep.CHOICE -> SetupStep.PASSWORD
            SetupStep.SHOW_WORDS, SetupStep.SKIP -> SetupStep.CHOICE
            SetupStep.CONFIRM -> SetupStep.SHOW_WORDS
            else -> step
        }
    }
    when (step) {
        SetupStep.PASSWORD -> CreatePasswordScreen(session, initial = password, title = stringResource(R.string.create_password_title)) {
            password = it; step = SetupStep.CHOICE
        }
        SetupStep.CHOICE -> RecoveryChoiceScreen(
            onRecoveryKey = { recovery?.close(); recovery = session.newRecoveryKey(); step = SetupStep.SHOW_WORDS },
            onNone = { step = SetupStep.SKIP },
            onBack = { step = SetupStep.PASSWORD },
        )
        SetupStep.SHOW_WORDS -> ShowWordsScreen(recovery!!, onDone = { step = SetupStep.CONFIRM }, onBack = { step = SetupStep.CHOICE })
        SetupStep.CONFIRM -> ConfirmWordsScreen(recovery!!, onConfirmed = { step = SetupStep.SECURING }, onShowAgain = { step = SetupStep.SHOW_WORDS })
        SetupStep.SKIP -> SkipRecoveryScreen(onConfirmed = {
            recovery?.close(); recovery = null; step = SetupStep.SECURING
        }, onBack = { step = SetupStep.CHOICE })
        SetupStep.SECURING -> SecuringScreen(onRun = { session.createVault(password.toCharArray(), recovery?.copy()) }, onFailed = { step = SetupStep.PASSWORD })
    }
}

private enum class SetupStep { PASSWORD, CHOICE, SHOW_WORDS, CONFIRM, SKIP, SECURING }

/** Also used after a recovery-key unlock and from Settings to change the password. */
@Composable
fun CreatePasswordScreen(
    session: VaultSession,
    initial: String = "",
    title: String,
    intro: String = stringResource(R.string.create_password_body),
    onBack: (() -> Unit)? = null,
    onDone: (String) -> Unit,
) {
    var pw by remember { mutableStateOf(initial) }
    var again by remember { mutableStateOf(initial) }
    var generated by remember { mutableStateOf<String?>(null) }
    val estimate = remember(pw) { PasswordStrength.estimate(pw) }
    val matches = pw == again
    val ok = estimate.bits >= PasswordStrength.REQUIRED_BITS && matches

    Page(title = title, onBack = onBack, bottomBar = { PrimaryButton(stringResource(R.string.continue_label), { onDone(pw) }, enabled = ok) }) {
        Body(intro)
        Spacer(Modifier.height(12.dp))
        SecretField(pw, { pw = it; generated = null }, stringResource(R.string.password_label), imeAction = ImeAction.Next)
        StrengthMeter(estimate)
        SecretField(
            again, { again = it }, stringResource(R.string.password_again_label),
            isError = again.isNotEmpty() && !matches,
            supporting = if (again.isNotEmpty() && !matches) stringResource(R.string.passwords_differ) else null,
        )
        Spacer(Modifier.height(8.dp))
        SecondaryButton(stringResource(R.string.generate_passphrase), {
            val p = Passphrase.generate(session.primitives); pw = p; again = p; generated = p
        })
        generated?.let {
            Spacer(Modifier.height(12.dp))
            Text(
                it, style = MaterialTheme.typography.titleMedium.copy(fontFamily = SourceCodePro), color = MaterialTheme.colorScheme.onSurface,
                modifier = Modifier.fillMaxWidth().background(MaterialTheme.colorScheme.surface, RoundedCornerShape(12.dp)).padding(16.dp),
            )
            Quiet(stringResource(R.string.generated_hint), Modifier.padding(top = 6.dp))
        }
        Spacer(Modifier.height(12.dp))
        InfoCard(null, stringResource(R.string.password_warning), R.drawable.ic_warning, warning = true)
        Quiet(stringResource(R.string.check_screen))
    }
}

@Composable
private fun RecoveryChoiceScreen(onRecoveryKey: () -> Unit, onNone: () -> Unit, onBack: () -> Unit) {
    Page(title = stringResource(R.string.recovery_title), onBack = onBack) {
        Body(stringResource(R.string.recovery_intro))
        Spacer(Modifier.height(12.dp))
        InfoCard(stringResource(R.string.recovery_key_option), stringResource(R.string.recovery_key_option_body), R.drawable.ic_check)
        PrimaryButton(stringResource(R.string.recovery_key_choose), onRecoveryKey)
